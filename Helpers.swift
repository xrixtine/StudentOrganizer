import UIKit

extension UIViewController {
    /// Shows a one-button alert. Used by the forms to explain why a save was refused.
    func showAlert(title: String, message: String) {
        let alert = UIAlertController(title: title, message: message,
                                      preferredStyle: .alert)
        alert.addAction(UIAlertAction(title: "OK", style: .default))
        present(alert, animated: true)
    }
}

extension UIImage {
    /// Returns a smaller copy whose longest side is at most `maxDimension` pixels.
    /// Camera photos are several thousand pixels wide; shrinking them before saving
    /// keeps the database small and the Notes grid fast.
    func resized(maxDimension: CGFloat) -> UIImage {
        let longestSide = max(size.width, size.height)
        guard longestSide > maxDimension else { return self }

        let scale = maxDimension / longestSide
        let newSize = CGSize(width: size.width * scale, height: size.height * scale)

        let format = UIGraphicsImageRendererFormat.default()
        format.scale = 1   // 1 point = 1 pixel, so the output is exactly newSize pixels
        return UIGraphicsImageRenderer(size: newSize, format: format).image { _ in
            self.draw(in: CGRect(origin: .zero, size: newSize))
        }
    }
}
